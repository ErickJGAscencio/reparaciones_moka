class Cliente {
  final int id;
  final String nombre;
  final String telefono;
  final String correo;
  final String direccion;
  final String notas;
  const Cliente({
    required this.id,
    required this.nombre,
    required this.telefono,
    required this.correo,
    required this.direccion,
    required this.notas,
  });
}
